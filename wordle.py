def main():
    play = accept_game()
    
    if play:
        load_game()
    else:
        sys.exit()
        
    while True:
        play_game()
        
        play_again = play_another_round()
        
        if not play_again:
            display_exit_message()
            sys.exit()


def accept_game():
    """
    Ask user if they would like to play and return their response.
    """
    while True:
        player_accept = input("Would you like to play Wordle? (y/n)\n")
        
        if player_accept.casefold() not in ["y", "n"]:
            print("\nInvalid entry. Please enter 'y' or 'n'.\n")
            continue
            
        return player_accept.casefold() == "y"
        
        
def load_game():
    """
    Display information about the game.
    """
    loading_info = "Welcome to Wordle."
    loading_info += "\nTry to guess the word the computer generates."
    loading_info += "\nYou have 5 chances."
    loading_info += "\nYou can get hints if you get stuck."
    loading_info += "\nHave fun!\n"
    
    print("\n")
    print("Wordle".upper().center(15, "="))
    print("\n", f"{loading_info}")
    
    
def play_game():
    """
    Gameplay for 1 round of Wordle.
    """
    # player selects difficulty
    difficulty_levels = list(GAME_DIFFICULTY_LEVELS.keys())
    
    difficulty = select_difficulty_level(difficulty_levels)
    
    print(f"\nGame difficulty: {difficulty}".upper())
    
    
    # word is generated by comp
    word_to_guess = generate_word(GAME_DIFFICULTY_LEVELS[difficulty])
    
    word_length = len(word_to_guess)
    
    revealed_letters = ["_"] * word_length
    
    print_formatted(revealed_letters)
    
    print("\nThe word has been generated. Try to guess it.\n")
    
    attempts = 5
    while attempts > 0:
        # player tries to guess the word
        player_guess = player_attempt(word_length)
    
        # evaluate whether player entry matches the generated word and display the results
        # green for a letter in the right place
        # yellow for a letter that's in the word but not in the right place
        # gray for an incorrect letter
        feedback = evaluate_player_guess(player_guess, word_to_guess)
        display_feedback(player_guess, feedback)
        
        attempts -= 1
        
        if all(mark == "G" for mark in feedback):
            win_game()
            break
        else:
            try_again(attempts)
            
        get_hint = False
        if attempts <= 3:
            get_hint = want_hint()
            
        if get_hint:
            to_display = reveal_letter(word_to_guess, revealed_letters, feedback)
            print_formatted(to_display)
    
    reveal_word(word_to_guess)
    
    
def select_difficulty_level(levels):
    """
    Ask the player to choose a difficulty level to play and return their response.
    """
    invalid_entry_message = f"\nInvalid entry. Please enter a number between 1 and {len(levels)}."
    
    print("\n")
    print("Difficulty levels:".upper().center(22, "="))
    for index, level in enumerate(levels, start=1):
        print(f"{index})\t{level.capitalize()}")
    print("\n")
    
    while True:
        game_level = input("\nSelect difficulty:\n")
        
        # validate user response
        if not game_level.isdecimal() or int(game_level) not in range(1, len(levels) + 1):
            print(invalid_entry_message)
            continue
            
        return levels[int(game_level) - 1]
        
        
def generate_word(word_list):
    """
    Generate the word that the player is to guess and return it.
    """
    return random.choice(word_list).casefold()
    
    
def print_formatted(chars):
    print()
    print(" | ".join(chars))
    
    
def player_attempt(wordlength):
    """
    Ask the player to enter a word of a given length and return it.
    """
    while True:
        guess = input(f"\nTry to guess the word. (Please enter a {wordlength}-letter word).\n\t>> ").strip()
        
        # validate user input
        if not guess.isalpha() or len(guess) != wordlength:
            print(f"\nInvalid entry. Please enter a {wordlength}-letter word.")
            continue
            
        return guess.casefold()
        
        
def evaluate_player_guess(guess, reference_word):
    """
    Evaluate the player's attempt against the reference word letter by letter and assign the results of
    the comparison to a list. 'G' for a letter in the right position, 'Y' for a letter in the wrong position,
    '_' for letters that are not in the reference word.
    """
    feedback = ["_"] * len(guess)
    
    remaining_letters = list(reference_word)
    
    # pass 1: marks 'G' first
    for n in range(len(guess)):
        if guess[n] == reference_word[n]:
            feedback[n] = "G"
            remaining_letters[n] = None
            
    # pass 2: marks 'Y'
    
    for n in range(len(guess)):
        if feedback[n] == "G":
            continue
        if guess[n] in remaining_letters:
            feedback[n] = "Y"
            remaining_letters[n] = None
            
    return feedback
    
    
def display_feedback(guess, feedback):
    GREEN = "\033[42m\033[30m"
    YELLOW = "\033[43m\033[30m"
    GRAY = "\033[100m\033[37m"
    RESET = "\033[0m"
    
    print()
    for letter, mark in zip(guess.upper(), feedback):
        color = GREEN if mark == "G" else YELLOW if mark == "Y" else GRAY
        print(f"{color} {letter} {RESET} ", end=" ")
    print("\n")
    
    
def win_game():
    """
    Display a congratulatory message if the player guesses the word correctly.
    """
    print("\nCongratulations! You managed to figure out the word!\n")
    
    
def try_again(attempts):
    """
    Display a short message to the player telling them to try again.
    """
    if attempts > 0:
        print("\nTry again!")
        print(f"You have {attempts} tries left!\n" if attempts != 1 else f"You have {attempts} try left!\n")
    else:
        print("\nSorry! You have run out of tries!\n")
        
        
def want_hint():
    """
    Ask the player if they want a hint and return their response.
    """
    while True:
        get_hint = input("\nWant a hint? (y/n)\n")
        
        if get_hint.casefold() not in ["y", "n"]:
            print("\nInvalid entry! Please enter 'y' or 'n'.\n")
            continue
            
        return get_hint.casefold() == "y"
        
        
def reveal_letter(word, revealed_letters, feedback):
    """
    Reveal a letter in the word to give the player a hint.
    """
    candidates = [n for n, mark in enumerate(feedback) if mark != "G" and revealed_letters[n] == "_"]
    
    if not candidates:
        return revealed_letters
        
    i = random.choice(candidates)
    revealed_letters[i] = word[i]
    return revealed_letters
    
    
def reveal_word(word):
    """
    Reveal the word that the player was supposed to guess.
    """
    print(f"\nWORD REVEAL: {word.upper()}\n")
    
    
def play_another_round():
    """
    Ask the user if they would like to play another round and return their response.
    """
    while True:
        play_again = input("\nWould you like to play again? (y/n)\n")
        
        if play_again.casefold() not in ["y", "n"]:
            print("\nInvalid entry. Please enter 'y' or 'n'.\n")
            continue
            
        return play_again.casefold() == "y"
        
        
def display_exit_message():
    """
    Display a short message before closing the program.
    """
    print("\nThanks for playing! We hope you enjoyed it!")
    
    
if __name__ == "__main__":
    main()